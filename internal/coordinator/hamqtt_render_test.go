// --- validation --------------------------------------------------------

// hamqttOrigin is the origin every payload carries, per F7. It is the
// production value and not a test literal: a test-only origin would let
// the shipped path and the render path disagree on the one block that
// decides whether a bundle is published at all.
func hamqttOrigin() discovery.Origin { return hass.HamqttOrigin() }

// TestHamqttPayloadsPassDiscoveryValidate runs every rendered payload
// through the schema check the library applies.
//
// The measurement recorded 18 refusals, all `button`, for `state_topic`
// and `optimistic` — two keys the MQTT button schema does not declare,
// emitted because neither of this repository's own struct fields had
// `omitempty`. Step 2 fixed both. This confirms the refusals are gone,
// and it is the check that gates step 6: a blocking result means the
// bundle is not published at all, so the device loses every entity
// rather than one key.
func TestHamqttPayloadsPassDiscoveryValidate(t *testing.T) {
	t.Parallel()

	checked, advisory := 0, 0
	refusals := map[string]int{}
	for _, sc := range surfaceScenarios() {
		comps, err := scenarioDiscovery(t, sc).RenderHamqtt(buildHamqttInputs(t, sc))
		if err != nil {
			t.Fatalf("RenderHamqtt: %v", err)
		}
		for _, c := range comps {
			var body map[string]any
			if err := json.Unmarshal(c.Body, &body); err != nil {
				t.Fatalf("decode %s: %v", c.Topic, err)
			}
			checked++
			err := discovery.ValidateBody(c.Platform, body)
			if err == nil {
				continue
			}
			var ve *discovery.ValidationError
			if errors.As(err, &ve) && !ve.Blocking() {
				advisory++
				t.Logf("%s: advisory: %v", c.Topic, err)
				continue
			}
			refusals[fmt.Sprintf("%s: %v", c.Platform, err)]++
		}
	}
	if checked != hamqttTotalConfigs {
		t.Errorf("validated %d payloads, want %d", checked, hamqttTotalConfigs)
	}
	for _, k := range sortedKeys(refusals) {
		t.Errorf("%d payloads refused: %s", refusals[k], k)
	}
	t.Logf("%d payloads validated: %d refused, %d advisory", checked, len(refusals), advisory)
}

// TestHamqttBundlesValidate is the same question in the form step 6
// would publish, which is the form where a refusal is expensive: an
// invalid bundle publishes nothing at all, so one bad component costs
// its device every entity it has.
//
// It also answers the measurement's open question about
// `device_tracker` as far as a unit test can: three of the 315 configs
// are trackers, a platform no other bridge in the programme publishes,
// and they are carried inside a client's bundle here. What remains is
// the runtime half — whether Home Assistant itself accepts a bundle
// component on that platform — which only a live console can settle.
func TestHamqttBundlesValidate(t *testing.T) {
	t.Parallel()

	bundles, components, trackers := 0, 0, 0
	for _, sc := range surfaceScenarios() {
		rendered, err := scenarioDiscovery(t, sc).
			HamqttBundles(buildHamqttInputs(t, sc), hamqttOrigin())
		if err != nil {
			t.Fatalf("%s: HamqttBundles: %v", sc.name, err)
		}
		for _, b := range rendered {
			bundles++
			components += len(b.Components)
			for _, key := range b.Keys() {
				if b.Components[key].Platform == hacatalog.PlatformDeviceTracker {
					trackers++
				}
			}
			if err := discovery.Validate(b); err != nil {
				var ve *discovery.ValidationError
				if errors.As(err, &ve) && !ve.Blocking() {
					t.Logf("%s: bundle %s: advisory: %v", sc.name, b.NodeID, err)
					continue
				}
				t.Errorf("%s: bundle %s is refused, so it would publish NO entities at all: %v",
					sc.name, b.NodeID, err)
			}
		}
	}
	if components != hamqttTotalConfigs {
		t.Errorf("bundles carry %d components, want %d", components, hamqttTotalConfigs)
	}
	const wantTrackers = 9
	if trackers != wantTrackers {
		t.Errorf("bundles carry %d device_tracker components, want %d", trackers, wantTrackers)
	}
	t.Logf("%d bundles, %d components, %d device_tracker components, all accepted",
		bundles, components, trackers)
}

// go-hamqtt v0.34.0's discovery.CheckBundleAvailability was weighed
// here and declined. It states, in the library's vocabulary, that no
// component may list an availability topic the consumer does not
// publish — measurement F8's trap, and the fix for two bridges in the
// fan-out that shipped a greyed-out fleet. This repository already
// asserts the same property, on the stronger side: TestAvailabilityModelIsTwoLevel
// requires every second availability source of every *published*
// config to be a topic the daemon wrote, and carries the 128/187 split
// as a literal. Written and mutation-tested rather than argued: the
// F8 mutation (hamqttLayout.Availability returning a dedicated
// "<uid>/availability" topic) is caught by five assertions, four of
// which predate any use of the new call, and the sixth added nothing.

// TestHamqttBundlesWithoutAnOriginAreRefused pins why the per-entity
// render passes a zero origin and the bundle form cannot.
//
// The zero origin is what keeps 315 payloads free of an `origin` block
// they do not carry today; a bundle with the same zero origin is
// refused outright. Both halves are load-bearing and they pull in
// opposite directions, so both are asserted.
func TestHamqttBundlesWithoutAnOriginAreRefused(t *testing.T) {
	t.Parallel()

	sc := surfaceScenarios()[2]
	bundles, err := scenarioDiscovery(t, sc).
		HamqttBundles(buildHamqttInputs(t, sc), discovery.Origin{})
	if err != nil {
		t.Fatalf("HamqttBundles: %v", err)
	}
	for _, b := range bundles {
		err := discovery.Validate(b)
		if err == nil {
			t.Errorf("bundle %s validates with no origin; step 7's origin block is no longer "+
				"a prerequisite for step 6 and the sequencing can be revisited", b.NodeID)
			continue
		}
		if !strings.Contains(err.Error(), "origin.name") {
			t.Errorf("bundle %s is refused for something other than the missing origin: %v",
				b.NodeID, err)
		}
	}
}

// TestHamqttPerEntityPayloadsCarryTheOrigin is the other half, on the
// bytes rather than on the validator.
//
// Step 4 asserted the opposite: the per-entity payloads carried no
// origin, because the shipped ones did not. F7 inverted it — every
// config on every plane now carries exactly {"name": "go-unifi2mqtt"},
// and nothing more, so the retained bytes do not move with the version
// the binary was linked at.
func TestHamqttPerEntityPayloadsCarryTheOrigin(t *testing.T) {
	t.Parallel()

	want := map[string]any{"name": hass.OriginName}
	seen := 0
	for _, sc := range surfaceScenarios() {
		comps, err := scenarioDiscovery(t, sc).RenderHamqtt(buildHamqttInputs(t, sc))
		if err != nil {
			t.Fatalf("RenderHamqtt: %v", err)
		}
		for _, c := range comps {
			var body map[string]any
			if err := json.Unmarshal(c.Body, &body); err != nil {
				t.Fatalf("decode %s: %v", c.Topic, err)
			}
			got, ok := body["origin"].(map[string]any)
			if !ok {
				t.Errorf("%s carries no origin block; a bundle of it would be refused", c.Topic)
				continue
			}
			if !reflect.DeepEqual(got, want) {
				t.Errorf("%s origin = %v, want %v", c.Topic, got, want)
			}
			seen++
			if _, ok := body["platform"]; ok {
				t.Errorf("%s carries a platform key, which belongs to the bundle form only", c.Topic)
			}
		}
	}
	if seen != hamqttTotalConfigs {
		t.Errorf("checked the origin on %d configs, want %d", seen, hamqttTotalConfigs)
	}
}

// --- the site device's two names ---------------------------------------

// TestHamqttSiteDeviceIsAnnouncedUnderOneName is F14, fixed.
//
// Step 4 found "unifi_site_default" announced as "UniFi Site Default"
// by the seven health entities, which took Site.Name, and as "UniFi
// Site default" by every SSID switch, which took Site.Internal. Per
// entity that was invisible last-write-wins in Home Assistant's device
// registry. A device bundle carries exactly ONE device block, so at
// step 6 one of the two would have won by collection order — which
// nothing stated, making the name a user sees a coin flip.
//
// Site.Name wins: Site.Internal is the API's addressing token and was
// never a display string. The SSID switches are the half that changes.
func TestHamqttSiteDeviceIsAnnouncedUnderOneName(t *testing.T) {
	t.Parallel()

	sc := surfaceScenarios()[2] // full.en: health and SSID switches both on
	d := scenarioDiscovery(t, sc)
	f := buildHamqttInputs(t, sc)

	if conflicts := d.HamqttDeviceBlockConflicts(f); len(conflicts) != 0 {
		t.Fatalf("device blocks still conflict on %d identities: %v", len(conflicts), conflicts)
	}

	// And the surviving name is the one F14 chose, on both planes —
	// "no conflict" would also be satisfied by both reading the wrong
	// field.
	const want = "UniFi Site Default"
	names := map[string]bool{}
	for _, e := range shippedSiteConfigs(t, d, f) {
		var body struct {
			Device struct {
				Name string `json:"name"`
			} `json:"device"`
		}
		if err := json.Unmarshal(e.Payload, &body); err != nil {
			t.Fatalf("decode %s: %v", e.ConfigTopic, err)
		}
		names[body.Device.Name] = true
	}
	if len(names) != 1 || !names[want] {
		t.Errorf("the site device is announced as %v, want exactly {%q}", sortedKeys(names), want)
	}
}

// shippedSiteConfigs returns every config the SHIPPED builders put on
// the synthetic site device: the health plane and the SSID switches,
// the two paths F14 made agree.
func shippedSiteConfigs(t *testing.T, d *hass.Discovery, f hass.HamqttFleet) []hass.Entry {
	t.Helper()
	out, err := d.Health()
	if err != nil {
		t.Fatalf("Health: %v", err)
	}
	if !f.ControlOpts.WLANEnable {
		t.Fatal("the scenario announces no SSID switches, so only one of the two paths is covered")
	}
	for i := range f.WLANs {
		e, err := d.WLANControl(&f.WLANs[i])
		if err != nil {
			t.Fatalf("WLANControl: %v", err)
		}
		out = append(out, e)
	}
	if len(out) < 8 {
		t.Fatalf("only %d site configs; both planes must be represented", len(out))
	}
	return out
}

