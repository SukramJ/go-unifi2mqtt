// The byte-equality proof — ADR 0070 phase 9, step 4.
//
// The question this file answers is the one the whole phase turns on:
// does go-hamqtt reproduce this bridge's published discovery payloads
// exactly, before step 6 makes the move irreversible? It is answered
// against the five pinned goldens on disk — never against the builders
// the library would replace, and never against a fixture this file
// regenerates. Nothing here consults -update-surface-golden; the flag
// is not reachable from any function in this file, and the five
// SHA-256 literals in surface_pin_test.go are untouched by this PR.
//
// Nothing published. [failingPublisher] is the assertion of that rather
// than a promise in a comment, and it drives every entry point the new
// path has.

// --- reading the pins ------------------------------------------------

// goldenConfigs returns a scenario's discovery plane as pinned on disk:
// config topic -> canonical encoding of the payload.
//
// It reads the golden FILE and never the builders. A comparison against
// output regenerated by the code under test proves only that the
// regeneration ran.
func goldenConfigs(t *testing.T, scenario string) map[string]string {
	t.Helper()
	path := filepath.Join("testdata", "surface", scenario+".json")
	raw, err := os.ReadFile(path) //nolint:gosec // fixed test fixture path
	if err != nil {
		t.Fatalf("read golden %s: %v", path, err)
	}
	var doc surfaceDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("decode golden %s: %v", path, err)
	}
	out := map[string]string{}
	for _, m := range doc.Messages {
		if !isConfigTopic(m.Topic) {
			continue
		}
		if m.JSON == nil {
			t.Fatalf("%s: config message %q carries no decoded payload", scenario, m.Topic)
		}
		b, err := json.Marshal(m.JSON)
		if err != nil {
			t.Fatalf("%s: re-encode %q: %v", scenario, m.Topic, err)
		}
		out[m.Topic] = string(b)
	}
	if len(out) == 0 {
		t.Fatalf("%s: the golden pins no discovery config at all", scenario)
	}
	return out
}

// canonicalBody re-encodes a rendered payload so both sides of every
// comparison are on the same footing: sorted keys, no formatting.
func canonicalBody(t *testing.T, body []byte) string {
	t.Helper()
	var obj map[string]any
	if err := json.Unmarshal(body, &obj); err != nil {
		t.Fatalf("rendered body is not JSON: %v\n%s", err, body)
	}
	b, err := json.Marshal(obj)
	if err != nil {
		t.Fatalf("re-encode: %v", err)
	}
	return string(b)
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// --- re-deriving the inputs -------------------------------------------

// buildHamqttInputs re-derives the discovery inputs of one scenario:
// the device snapshot the static loop announces from, the clients that
// passed the filter with their uplinks resolved, the SSID catalogue and
// the two option sets, gated exactly as the coordinator gates them.
//
// It re-derives rather than intercepts, which is only safe because
// TestHamqttInputsReproduceThePublishedConfigTopics feeds the same
// value to the SHIPPED builders and requires the golden back. A
// re-derivation that quietly differed — one client filtered out, one
// control off — would render a smaller entity set and let the
// byte-equality below prove something smaller than it claims.
func buildHamqttInputs(t *testing.T, sc surfaceScenario) hass.HamqttFleet {
	t.Helper()

	cfg, err := config.Load(strings.NewReader(sc.yaml), config.MapEnv{})
	if err != nil {
		t.Fatalf("scenario %s: config: %v", sc.name, err)
	}
	src := newFakeSource()
	sc.setup(src)
	if !cfg.ClassicEnable {
		src.healthErr = unifi.ErrCapabilityUnavailable
	}
	caps := capSet{}
	for _, c := range sc.caps {
		caps[c] = true
	}

	c := New(Deps{
		Cfg:          cfg,
		Site:         model.Site{ID: "site-uuid", Name: "Default", Internal: "default"},
		Source:       src,
		MQTT:         &fakeBroker{},
		Capabilities: caps,
		Info:         model.ControllerInfo{ApplicationVersion: "10.5.67"},
		Logger:       slog.New(slog.DiscardHandler),
		Now:          newFakeClock().now,
	})

	ctx := context.Background()
	// The static loop is what populates the detail snapshot, the
	// network catalogue and the device-id index the client filter and
	// the uplink resolution both read.
	if err := c.refreshStatic(ctx); err != nil {
		t.Fatalf("scenario %s: refreshStatic: %v", sc.name, err)
	}

	devices, err := src.DevicesWithDetails(ctx, c.site.ID)
	if err != nil {
		t.Fatalf("scenario %s: DevicesWithDetails: %v", sc.name, err)
	}
	wlans, err := src.WLANs(ctx, c.site.ID)
	if err != nil {
		t.Fatalf("scenario %s: WLANs: %v", sc.name, err)
	}

	var clients []model.Client
	if cfg.Clients.Enable {
		all, err := src.Clients(ctx, c.site.ID)
		if err != nil {
			t.Fatalf("scenario %s: Clients: %v", sc.name, err)
		}
		c.mu.RLock()
		networks, byID := c.networks, c.deviceIDToMAC
		c.mu.RUnlock()
		for i := range all {
			if id := all[i].UplinkID; id != "" {
				all[i].UplinkMAC = byID[id]
			}
		}
		clients = newClientFilter(&cfg.Clients, networks, slog.New(slog.DiscardHandler)).Apply(all)
	}

	return hass.HamqttFleet{
		Devices:        devices,
		Clients:        clients,
		WLANs:          wlans,
		ClientOpts:     hass.ClientOptions{Signal: c.clientSignalEnabled()},
		ControlOpts:    c.controlOptions(),
		AnnounceHealth: cfg.ClassicEnable,
	}
}

