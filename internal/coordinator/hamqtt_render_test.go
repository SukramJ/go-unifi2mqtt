// shippedConfigs renders the fleet through the SHIPPED builders, in the
// order the coordinator announces them.
func shippedConfigs(t *testing.T, d *hass.Discovery, f hass.HamqttFleet) map[string]string {
	t.Helper()
	out := map[string]string{}
	add := func(entries []hass.Entry) {
		for _, e := range entries {
			if _, dup := out[e.ConfigTopic]; dup {
				t.Fatalf("the shipped builders produced %q twice", e.ConfigTopic)
			}
			out[e.ConfigTopic] = canonicalBody(t, e.Payload)
		}
	}
	for i := range f.Devices {
		dev := &f.Devices[i]
		entries, err := d.Device(dev)
		if err != nil {
			t.Fatalf("Device: %v", err)
		}
		add(entries)
		controls, err := d.DeviceControls(dev, f.ControlOpts)
		if err != nil {
			t.Fatalf("DeviceControls: %v", err)
		}
		add(controls)
	}
	if f.ControlOpts.WLANEnable {
		for i := range f.WLANs {
			entry, err := d.WLANControl(&f.WLANs[i])
			if err != nil {
				t.Fatalf("WLANControl: %v", err)
			}
			add([]hass.Entry{entry})
		}
	}
	for i := range f.Clients {
		cl := &f.Clients[i]
		entries, err := d.Client(cl, f.ClientOpts)
		if err != nil {
			t.Fatalf("Client: %v", err)
		}
		add(entries)
		controls, err := d.ClientControls(cl, f.ControlOpts)
		if err != nil {
			t.Fatalf("ClientControls: %v", err)
		}
		add(controls)
	}
	if f.AnnounceHealth {
		entries, err := d.Health()
		if err != nil {
			t.Fatalf("Health: %v", err)
		}
		add(entries)
	}
	return out
}

// renderedConfigs renders the fleet through go-hamqtt.
func renderedConfigs(t *testing.T, d *hass.Discovery, f hass.HamqttFleet) map[string]string {
	t.Helper()
	comps, err := d.RenderHamqtt(f)
	if err != nil {
		t.Fatalf("RenderHamqtt: %v", err)
	}
	out := make(map[string]string, len(comps))
	for _, c := range comps {
		if _, dup := out[c.Topic]; dup {
			t.Fatalf("the library path rendered %q twice", c.Topic)
		}
		out[c.Topic] = canonicalBody(t, c.Body)
	}
	return out
}

// --- the experiment ---------------------------------------------------

// hamqttTotalConfigs is the whole pinned discovery plane: 315 configs
// across five scenarios.
//
// A Go literal, so shrinking the proof is a declaration in review
// rather than a quietly smaller number in a log line.
const hamqttTotalConfigs = 315

// F15's carve-out used to live here.
//
// Step 4 could not reproduce `"manufacturer": ""` on 36 client configs
// through the library — discovery.DeviceInfo.Manufacturer is
// `omitempty`, so an empty manufacturer renders as an absent key — and
// carved the one key out of the comparison under tight conditions
// rather than forcing it through Component.Extra["device"], which would
// have overridden exactly the part of the payload under test.
//
// The carve-out was temporary by construction and is gone: this bridge
// now omits the key too, so the comparison below is byte-equality on
// all 315 configs with no exceptions at all.

// TestHamqttReproducesThePublishedConfigs is the headline.
func TestHamqttReproducesThePublishedConfigs(t *testing.T) {
	t.Parallel()

	total, matched := 0, 0
	for _, sc := range surfaceScenarios() {
		want := goldenConfigs(t, sc.name)
		f := buildHamqttInputs(t, sc)
		got := renderedConfigs(t, scenarioDiscovery(t, sc), f)

		for _, topic := range sortedKeys(want) {
			total++
			g, ok := got[topic]
			if !ok {
				t.Errorf("%s: - the library renders no payload for the pinned topic %s", sc.name, topic)
				continue
			}
			if g == want[topic] {
				matched++
				continue
			}
			t.Errorf("%s: ~ %s\n  pinned   %s\n  rendered %s", sc.name, topic, want[topic], g)
		}
		for _, topic := range sortedKeys(got) {
			if _, ok := want[topic]; !ok {
				t.Errorf("%s: + the library renders a config this bridge does not publish: %s",
					sc.name, topic)
			}
		}
	}

	if total != hamqttTotalConfigs {
		t.Errorf("compared %d pinned configs, want %d", total, hamqttTotalConfigs)
	}
	if matched != hamqttTotalConfigs {
		t.Errorf("reproduced %d of %d pinned configs byte for byte, with no carve-outs left",
			matched, hamqttTotalConfigs)
	}
	t.Logf("byte-equal: %d of %d", matched, hamqttTotalConfigs)
}

// TestHamqttInputsReproduceThePublishedConfigTopics is what makes the
// proof above non-circular.
//
// buildHamqttInputs re-derives the discovery inputs from a warmed
// coordinator rather than intercepting them at the call site. A
// re-derivation that quietly differed from what the daemon announces
// would render a different entity set, and the comparison above would
// be proving something smaller than it claims. So the same value is fed
// to the SHIPPED builders and the golden is required back, whole.
func TestHamqttInputsReproduceThePublishedConfigTopics(t *testing.T) {
	t.Parallel()

	checked := 0
	for _, sc := range surfaceScenarios() {
		want := goldenConfigs(t, sc.name)
		f := buildHamqttInputs(t, sc)
		got := shippedConfigs(t, scenarioDiscovery(t, sc), f)

		if len(got) != len(want) {
			t.Errorf("%s: the re-derived inputs produce %d configs, the golden pins %d",
				sc.name, len(got), len(want))
		}
		for _, topic := range sortedKeys(want) {
			checked++
			if got[topic] != want[topic] {
				t.Errorf("%s: the re-derived inputs do not reproduce %s\n  golden %s\n  got    %s",
					sc.name, topic, want[topic], got[topic])
			}
		}
	}
	if checked != hamqttTotalConfigs {
		t.Errorf("checked %d configs, want %d", checked, hamqttTotalConfigs)
	}
}

// --- the topic form ---------------------------------------------------

// TestHamqttRetractionReproducesEveryPublishedConfigTopic is F5,
// settled against running code rather than against the documentation.
//
// publisher.SupersededTopics' default form renders
// <prefix>/<platform>/<bundle.NodeID>/<component key>/config. Both
// inputs are step-4 modelling choices, so this asserts the two that
// matter — the node id IS device.identifiers[0] and the component key
// IS the object-id segment — over every config the bridge publishes,
// and asserts that the other candidate form reproduces NONE of them.
// publisher.Config.LegacyEntityTopics REPLACES the default rather than
// extending it, so naming LegacyTopicByUniqueID at step 6 would turn a
// working retraction into no retraction at all.
func TestHamqttRetractionReproducesEveryPublishedConfigTopic(t *testing.T) {
	t.Parallel()

	withNodeID := func(prefix, platform, nodeID, key, _ string) string {
		return prefix + "/" + platform + "/" + nodeID + "/" + key + "/config"
	}
	byUniqueID := func(prefix, platform, _, _, uniqueID string) string {
		return prefix + "/" + platform + "/" + uniqueID + "/config"
	}

	matched, unmatchedByUID, divergentUID := 0, 0, 0
	for _, sc := range surfaceScenarios() {
		want := goldenConfigs(t, sc.name)
		f := buildHamqttInputs(t, sc)
		comps, err := scenarioDiscovery(t, sc).RenderHamqtt(f)
		if err != nil {
			t.Fatalf("RenderHamqtt: %v", err)
		}
		for _, c := range comps {
			var body map[string]any
			if err := json.Unmarshal(c.Body, &body); err != nil {
				t.Fatalf("decode %s: %v", c.Topic, err)
			}
			dev, _ := body["device"].(map[string]any)
			ids, _ := dev["identifiers"].([]any)
			if len(ids) == 0 {
				t.Fatalf("%s: rendered no device identifier", c.Topic)
			}
			identifier, _ := ids[0].(string)
			if c.NodeID != identifier {
				t.Errorf("%s: bundle node id %q is not device.identifiers[0] %q — "+
					"the default retraction form would retract nothing",
					c.Topic, c.NodeID, identifier)
			}
			uniqueID, _ := body["unique_id"].(string)

			parts := strings.Split(c.Topic, "/")
			got := withNodeID(parts[0], string(c.Platform), c.NodeID, c.Key, uniqueID)
			if _, pinned := want[c.Topic]; !pinned {
				t.Fatalf("%s is not a pinned topic", c.Topic)
			}
			if got != c.Topic {
				t.Errorf("the five-segment node-id form renders %q, want %q", got, c.Topic)
				continue
			}
			matched++
			if byUniqueID(parts[0], string(c.Platform), c.NodeID, c.Key, uniqueID) != c.Topic {
				unmatchedByUID++
			}
			if uniqueID != c.NodeID+"_"+c.Key {
				divergentUID++
			}
		}
	}

	if matched != hamqttTotalConfigs {
		t.Errorf("the default form reproduced %d of %d published config topics",
			matched, hamqttTotalConfigs)
	}
	if unmatchedByUID != matched {
		t.Errorf("the by-unique_id form reproduces %d of %d published topics; "+
			"if the two candidates are no longer distinguishable this test proves nothing",
			matched-unmatchedByUID, matched)
	}
	// The 21 of F5: the component key cannot be derived from the unique
	// id, because on these it is not its suffix.
	const wantDivergentUID = 21
	if divergentUID != wantDivergentUID {
		t.Errorf("unique_id != <node_id>_<key> on %d configs, want %d", divergentUID, wantDivergentUID)
	}
	if hass.LegacyConfigTopicForm != "<discovery_prefix>/<platform>/<node_id>/<object_id>/config" {
		t.Errorf("hass.LegacyConfigTopicForm = %q, which is no longer the form this test proves",
			hass.LegacyConfigTopicForm)
	}
}

