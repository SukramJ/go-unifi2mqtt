// The published-surface pin (ADR 0070 phase 9, step 0).
//
// What this file captures is everything this daemon puts on a broker:
// every topic, the payload, the QoS and the retain flag, in one row per
// message, for a handful of scenarios that between them reach every
// builder in the tree. It exists so the phase-9 migration onto
// go-hamqtt can be proved byte-equal rather than argued to be.
//
// Three properties make it load-bearing rather than decorative:
//
//   - The messages come from the real coordinator driving the real
//     internal/hass builders. Only the console (Source) and the broker
//     (Publisher) are stubbed; nothing that composes a topic or a
//     payload is.
//   - QoS and retain are read off the transport call, not off a
//     constant, so a change to what publishConfig passes shows up here
//     even if the constant it was named after did not move.
//   - The digests in goldenDigests are held outside the golden files
//     and -update-surface-golden deliberately never writes them: a
//     golden regenerated by the very code it guards is invisible to the
//     run that regenerates it, so the only thing that can make a
//     regeneration visible is a value a human has to paste in.
//
// See notes/adr0070-phase9-measurement.md for what was measured here.

var updateSurfaceGolden = flag.Bool("update-surface-golden", false,
	"rewrite internal/coordinator/testdata/surface/*.json, print the new digests and fail")

// versionPlaceholder stands in for version.Version in the bridge info
// payload. It is the one value in the surface that moves with every
// release for reasons that have nothing to do with the published shape,
// and pinning it would make every version bump rewrite the goldens.
const versionPlaceholder = "<bridge-version>"

// recordedMsg is one publish: topic, delivery guarantee and payload in
// a single row, so a topic move, a payload change and a QoS/retain
// change are all one diff.
//
// The payload is stored decoded — JSON as JSON, scalars as text — so a
// reviewer reads the config rather than an escaped blob, and so the
// comparison can be made on a canonical re-encoding that is immune to
// key order and line endings.
type recordedMsg struct {
	Topic  string         `json:"topic"`
	QoS    int            `json:"qos"`
	Retain bool           `json:"retain"`
	JSON   map[string]any `json:"json,omitempty"`
	Text   *string        `json:"text,omitempty"`
	Empty  bool           `json:"empty,omitempty"`
}

// surfaceDoc is one scenario's whole published surface.
type surfaceDoc struct {
	Scenario string        `json:"scenario"`
	Messages []recordedMsg `json:"messages"`
}

// --- scenarios -------------------------------------------------------

// surfaceScenario is one installation shape.
type surfaceScenario struct {
	name string
	// yaml is the operator config, on top of the shipped defaults.
	yaml string
	// caps lists the classic-layer capabilities that are live.
	caps []unifi.Capability
	// devices/details/clients/wlans/health replace the defaults when set.
	setup func(s *fakeSource)
}

// capSet is a Capabilities over a fixed list.
type capSet map[unifi.Capability]bool

func (c capSet) Has(x unifi.Capability) bool { return c[x] }

