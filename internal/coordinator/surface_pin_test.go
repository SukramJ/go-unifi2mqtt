// --- driving the real builders ---------------------------------------

// buildSurface runs one scenario through the real coordinator and
// returns every message it published.
//
// Nothing between the console and the broker is replaced: the
// coordinator composes the topics, internal/hass renders the payloads,
// and publish.go decides the QoS and the retain flag.
func buildSurface(t *testing.T, sc surfaceScenario) surfaceDoc {
	t.Helper()

	cfg, err := config.Load(strings.NewReader(sc.yaml), config.MapEnv{})
	if err != nil {
		t.Fatalf("scenario %s: config: %v", sc.name, err)
	}

	src := newFakeSource()
	sc.setup(src)
	if !cfg.ClassicEnable {
		// Without the classic layer the facade reports the health
		// endpoint as absent, which is what keeps the site entities
		// unannounced.
		src.healthErr = unifi.ErrCapabilityUnavailable
	}

	caps := capSet{}
	for _, c := range sc.caps {
		caps[c] = true
	}

	broker := &fakeBroker{}
	clock := newFakeClock()
	c := New(Deps{
		Cfg:          cfg,
		Site:         model.Site{ID: "site-uuid", Name: "Default", Internal: "default"},
		Source:       src,
		MQTT:         broker,
		Capabilities: caps,
		Info:         model.ControllerInfo{ApplicationVersion: "10.5.67"},
		Logger:       slog.New(slog.DiscardHandler),
		Now:          clock.now,
	})

	ctx := context.Background()
	// The order the daemon itself uses: the connect hook, then the
	// static loop (which announces discovery), then the fast loops.
	c.OnConnect(ctx)
	if err := c.refreshStatic(ctx); err != nil {
		t.Fatalf("scenario %s: refreshStatic: %v", sc.name, err)
	}
	if err := c.refreshDevices(ctx); err != nil {
		t.Fatalf("scenario %s: refreshDevices: %v", sc.name, err)
	}
	if err := c.refreshDeviceStats(ctx); err != nil {
		t.Fatalf("scenario %s: refreshDeviceStats: %v", sc.name, err)
	}
	// Gated exactly as Run gates them, so a scenario cannot publish a
	// plane its config would not have started a loop for.
	if cfg.Clients.Enable {
		if err := c.refreshClients(ctx); err != nil {
			t.Fatalf("scenario %s: refreshClients: %v", sc.name, err)
		}
	}
	if cfg.ClassicEnable {
		if err := c.refreshHealth(ctx); err != nil {
			t.Fatalf("scenario %s: refreshHealth: %v", sc.name, err)
		}
	}

	return surfaceDoc{Scenario: sc.name, Messages: recordMessages(t, broker)}
}

// recordMessages turns the recorded publishes into golden rows, sorted
// by topic so a concurrent stats fan-out cannot reorder the document.
func recordMessages(t *testing.T, b *fakeBroker) []recordedMsg {
	t.Helper()
	b.mu.Lock()
	msgs := slices.Clone(b.msgs)
	b.mu.Unlock()

	out := make([]recordedMsg, 0, len(msgs))
	for _, m := range msgs {
		row := recordedMsg{Topic: m.topic, QoS: int(m.qos), Retain: m.retain}
		payload := m.payload
		switch {
		case payload == "":
			row.Empty = true
		case strings.HasPrefix(payload, "{"):
			var obj map[string]any
			if err := json.Unmarshal([]byte(payload), &obj); err != nil {
				t.Fatalf("payload on %s is not JSON: %v", m.topic, err)
			}
			if v, ok := obj["bridge_version"]; ok && v == version.Version {
				obj["bridge_version"] = versionPlaceholder
			}
			row.JSON = obj
		default:
			text := payload
			row.Text = &text
		}
		out = append(out, row)
	}
	slices.SortStableFunc(out, func(a, b recordedMsg) int { return strings.Compare(a.Topic, b.Topic) })
	return out
}

// --- the golden test -------------------------------------------------

func TestPublishedSurfaceGolden(t *testing.T) {
	t.Parallel()

	if *updateSurfaceGolden {
		regenerateSurfaceGoldens(t)
		return
	}

	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			t.Parallel()
			got := canonical(t, buildSurface(t, sc))
			want, err := os.ReadFile(surfaceGoldenPath(sc.name))
			if err != nil {
				t.Fatalf("read golden: %v (run with -update-surface-golden)", err)
			}
			var stored surfaceDoc
			if err := json.Unmarshal(want, &stored); err != nil {
				t.Fatalf("golden is not valid JSON: %v", err)
			}
			// Compared on canonical re-encoding, so key order,
			// indentation and line endings cannot decide the result.
			if !bytes.Equal(got, canonical(t, stored)) {
				t.Errorf("published surface changed for %s\n--- got\n%s", sc.name, got)
			}
		})
	}
}

// TestPublishedSurfaceDigests is what makes a regeneration visible.
//
// The digest is taken over the canonical encoding of the *rebuilt*
// scenario, not over the golden file's bytes, so it is immune to
// checkout differences as well as to reformatting — and it lives here,
// in Go, where -update-surface-golden cannot reach it.
func TestPublishedSurfaceDigests(t *testing.T) {
	t.Parallel()
	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			t.Parallel()
			got := surfaceDigest(t, buildSurface(t, sc))
			want, ok := goldenDigests[sc.name]
			if !ok {
				t.Fatalf("no digest recorded for %s: got %s", sc.name, got)
			}
			if got != want {
				t.Errorf("surface digest for %s changed\n got: %s\nwant: %s\n"+
					"If this is intended, regenerate the goldens, review the diff, "+
					"and paste the new literal into goldenDigests in the same commit.",
					sc.name, got, want)
			}
		})
	}
}

func surfaceDigest(t *testing.T, doc surfaceDoc) string {
	t.Helper()
	sum := sha256.Sum256(canonical(t, doc))
	return hex.EncodeToString(sum[:])
}

// canonical re-encodes a document through encoding/json, which sorts
// object keys, so two semantically identical documents produce
// identical bytes.
func canonical(t *testing.T, doc surfaceDoc) []byte {
	t.Helper()
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatalf("encode: %v", err)
	}
	return append(b, '\n')
}

func surfaceGoldenPath(name string) string {
	return filepath.Join("testdata", "surface", name+".json")
}

// regenerateSurfaceGoldens rewrites every golden, prints the digests
// and fails.
//
// The failure is the point: the digest map is not written, so a human
// has to paste the new literals in, in the same commit, whose message
// has to name the finding that moved the bytes.
func regenerateSurfaceGoldens(t *testing.T) {
	t.Helper()
	var b strings.Builder
	b.WriteString("goldens rewritten; paste these into goldenDigests:\n\n")
	b.WriteString("var goldenDigests = map[string]string{\n")
	for _, sc := range surfaceScenarios() {
		doc := buildSurface(t, sc)
		if err := os.WriteFile(surfaceGoldenPath(sc.name), canonical(t, doc), 0o600); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", sc.name, surfaceDigest(t, doc))
	}
	b.WriteString("}\n")
	t.Fatal(b.String())
}

